    end
  end

  for i = 1, 4 do
    DATA[i].STATUS = self:getStorageValue(730024 + i)
    DATA[i].OWN = self:getStorageValue(DATA[i].STORAGE)
  end

  self:sendExtendedOpcode(ExtendedOPCodes.CODE_DAILYQUEST, json.encode({ action = "GETTRACKERINFO", data = DATA }))
  return true
end

function Player:getQuestLevel()
  return self:getStorageValue(730029)
end

function Player:getNewQuests()
  local PLAYER_LEVEL = nil
  if self:getLevel() >= 100 then
    PLAYER_LEVEL = math.floor(self:getLevel() / 100) * 100
  else
    PLAYER_LEVEL = self:getLevel()
  end

  local COUNT = #DAILY_QUEST_LEVELS
  for i = 1, #DAILY_QUEST_LEVELS do
    if PLAYER_LEVEL <= DAILY_QUEST_LEVELS[i] then
      self:setStorageValue(730029, i)
      break
    elseif i == COUNT then
      self:setStorageValue(730029, COUNT)
      break
    end
  end

  COUNT = 0
  for _ in pairs(DAILY_QUEST[self:getStorageValue(730029)]) do COUNT = COUNT + 1 end

  local NUMBERS = {}
  local TVALUE = 1
  math.randomseed(os.time())
  math.random(); math.random(); math.random()
  while true do
    NEWNUMBER = true
    VALUE = math.random(1, COUNT)
    if TVALUE > 1 then
      for k, v in pairs(NUMBERS) do
        if VALUE == v then
          NEWNUMBER = false
        end
      end
      if NEWNUMBER == true then
        NUMBERS[TVALUE] = VALUE
        TVALUE = TVALUE + 1
      end
    else
      NUMBERS[TVALUE] = VALUE
      TVALUE = TVALUE + 1
    end

    if TVALUE == 5 then
      break
    end
  end

  local QUESTES = ""

  self:setStorageValue(730020, 0)
  for k, v in pairs(NUMBERS) do
    self:setStorageValue(730020 + k, v)
    self:setStorageValue(730024 + k, 1)
    QUESTES = QUESTES .. tostring(v .. ",")
  end
  db.query("UPDATE `players` SET `daily_quest` = '" .. QUESTES .. "' WHERE `id` = " .. self:getGuid())
  self:clearData()
end

function Player:clearData()
  local DATA = {}
  for i = 1, 4 do
    local id = self:getStorageValue(730020 + i)
    table.insert(DATA, DAILY_QUEST[self:getQuestLevel()][id])
  end

  for i = 1, 4 do
    DATA[i].STATUS = self:getStorageValue(730024 + i)
    DATA[i].ID = self:getStorageValue(730020 + i)
  end

  DATA[1].BONUS = self:getStorageValue(730020)

  self:sendExtendedOpcode(ExtendedOPCodes.CODE_DAILYQUEST, json.encode({ action = "CLEARDATA", data = DATA }))
  return true
end
