function onExtendedOpcode(player, opcode, buffer)
  if opcode == ExtendedOPCodes.CODE_DAILYQUEST then
    local status, json_data =
        pcall(
          function()
            return json.decode(buffer)
          end
        )
    if not status then
      return false
    end

    if json_data.action == "OPEN" then
      player:getActiveQuests()
      return true
    end

    if json_data.action == "START" then
      player:startQuest(json_data.quest, json_data.number)
      return true
    end

    if json_data.action == "CLAIMBONUS" then
      player:claimBonus()
      return true
    end

    if json_data.action == "GETTRACKERINFO" then
      player:getActiveQuestsTracker()
      return true
    end
  end

  return false
end

function Player:getActiveQuests()
  local DATA = {}
  for i = 1, 4 do
    local id = self:getStorageValue(730020 + i)
    table.insert(DATA, DAILY_QUEST[self:getQuestLevel()][id])
  end

  for i = 1, 4 do
    DATA[i].STATUS = self:getStorageValue(730024 + i)
    DATA[i].ID = self:getStorageValue(730020 + i)
  end

  DATA[1].BONUS = self:getStorageValue(730020)

  self:sendExtendedOpcode(ExtendedOPCodes.CODE_DAILYQUEST, json.encode({ action = "OPEN", data = DATA }))
  return true
end

function Player:updateQuest(id, value)
  self:setStorageValue(DAILY_QUEST[self:getQuestLevel()][id].STORAGE,
    self:getStorageValue(DAILY_QUEST[self:getQuestLevel()][id].STORAGE) + value)

  if self:getStorageValue(DAILY_QUEST[self:getQuestLevel()][id].STORAGE) == DAILY_QUEST[self:getQuestLevel()][id].POINTS then
    self:completeQuest(id)
  end

  self:updateTracker(id)
  return true
end

function Player:startQuest(id, num)
  for i = 1, 4 do
    if self:getStorageValue(730024 + num) == 1 then
      self:setStorageValue(730024 + num, DAILY_QUEST[self:getQuestLevel()][id].STORAGE)
      self:setStorageValue(DAILY_QUEST[self:getQuestLevel()][id].STORAGE, 0)

      self:addTracker(id, num)
      self:getActiveQuests()
      return true
    end
  end
  self:getActiveQuests()
  return true
end

function Player:isQuestActive(id)
  for i = 1, 4 do
    if self:getStorageValue(730024 + i) == DAILY_QUEST[self:getQuestLevel()][id].STORAGE then
      return true
    end
  end
  return false
end

function Player:completeQuest(id)
  if self:getStorageValue(DAILY_QUEST[self:getQuestLevel()][id].STORAGE) == DAILY_QUEST[self:getQuestLevel()][id].POINTS then
    for i = 1, 4 do
      if self:getStorageValue(730024 + i) == DAILY_QUEST[self:getQuestLevel()][id].STORAGE then
        self:setStorageValue(730024 + i, 2)
      end
    end
    self:setStorageValue(730020, self:getStorageValue(730020) + 1)
    self:giveRewards(id)
  end
  return true
end

function Player:giveRewards(id)
  for i = 1, #DAILY_QUEST[self:getQuestLevel()][id].REWARD do
    if DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].TYPE == "exp" then
      self:addExperience(DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE, true)
      local xpRew = (DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE) / 100
      self:addExperience(getExpForLevel(self:getLevel() + xpRew) - self:getExperience(), true)
      local paragonLevel = self:getStorageValue(PlayerStorage.paragonLevel)
      local amount = ((self:getExperience() * 0.3) / 100) / 10
      if self:getLevel() >= 1500 then
        self:setStorageValue(PlayerStorage.paragonLevel, paragonLevel + 1) -- paragon level
        self:addStatsPoints(1)
        -- self:paragonUP(amount, true)
      end
    elseif DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].TYPE == "money" then
      self:setBankBalance(self:getBankBalance() + DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE)
      self:refreshBalance()
    elseif DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].TYPE == "item" then
      if DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[1] == 1 then
        addTierItem(self, DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[2], 100)
      elseif DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[1] == 2 then
        randomFragments(self, self, 1, 10, 1, 50, 1, 100000, DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[2], 50)
      elseif DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[1] == 3 then
        randomUpgradeMaterials(self, self, DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[2])
      elseif DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[1] == 4 then
        randomPotions(self, self, DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[2], false)
      elseif DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[1] == 5 then
        randomPotions(self, self, DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[2], true)
      end
      --      self:getInbox():addItem(DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[1], DAILY_QUEST[self:getQuestLevel()][id].REWARD[i].VALUE[2], INDEX_WHEREEVER, FLAG_NOLIMIT)
    end
  end

  local description = " {Daily Quest} Complete: " .. DAILY_QUEST[self:getQuestLevel()][id].NAME .. "\n"
  if self:getLevel() >= 1500 then
    description = string.format("%s %s", description, "Paragon Level: +1\n")
  else
    description = string.format("%s %s", description,
      "EXP: {" .. DAILY_QUEST[self:getQuestLevel()][id].REWARD[1].VALUE .. "}%\n")
  end
  description = string.format("%s %s", description,
    "GOLD: {" .. DAILY_QUEST[self:getQuestLevel()][id].REWARD[2].VALUE .. "}\n")
  description = string.format("%s %s", description, "ITEM: {Random Tier Item and Fragments}")
  self:sendTextMessage(MESSAGE_STATUS_CONSOLE_BLUE, description)
  self:sendExtendedOpcode(216, json.encode({ text = description, color = "#f7ef8a" }))
  return true
end

function Player:claimBonus()
  local timeBoosts = 1
  if self:getStorageValue(730020) == 4 then
    for i = 1, 7 do
      local buffConfig = { BUFF_EXP_BOOST, STORE_GOLD_BOOST, STORE_LOOT_BOOST, STORE_SKILL_BOOST,
        STORE_AUTOLOOT_INDIFITY, STORE_AUTOLOOT_RARITY, STORE_PORTALS_BOOST }
      local buffConfigNames = { "20% EXP", "20% GOLD", "20% LOOT", "100% SKILL", "Autoloot Identification",
        "Autoloot Pickup Rarity", "Special Spawn Chance" }
      local buff = player:getBuff(buffConfig[i])
      if buff then
        local time = time + (buff.endTime - (os.time() * 1000))
        player:say("Your +1 hours of " .. buffConfigNames .. " has extended!", TALKTYPE_MONSTER_SAY)
        player:addBuff(buffConfig[i], time)
        ExpShowTotal(player)
      else
        player:say("Your 1 hours of " .. buffConfigNames .. " has started!", TALKTYPE_MONSTER_SAY)
        player:addBuff(buffConfig[i], 3600000)
        ExpShowTotal(player)
      end
    end

    local description =
    "Here are the rewards for completing the Daily Quests!\nSelf {EXP} / {SKILL} / {GOLD} / {LOOT} / {SPAWN} boost and Auto Pickup Rarity/Identification for {" ..
    timeBoosts .. "} hours!"
    self:sendTextMessage(MESSAGE_STATUS_CONSOLE_BLUE, description)
    self:sendExtendedOpcode(216, json.encode({ text = description, color = "#f7ef8a" }))
    self:setStorageValue(730020, 0)
  end

  return true
end

function Player:addTracker(id, num)
  local DATA = DAILY_QUEST[self:getQuestLevel()][id]
  DATA.OWN = 0
  DATA.STATUS = self:getStorageValue(730024 + num)
  self:sendExtendedOpcode(ExtendedOPCodes.CODE_DAILYQUEST, json.encode({ action = "ADDTRACKER", data = DATA }))
  return true
end

function Player:updateTracker(id)
  local DATA = DAILY_QUEST[self:getQuestLevel()][id]
  DATA.OWN = self:getStorageValue(DATA.STORAGE)
  self:sendExtendedOpcode(ExtendedOPCodes.CODE_DAILYQUEST, json.encode({ action = "UPDATETRACKER", data = DATA }))
  return true
end

