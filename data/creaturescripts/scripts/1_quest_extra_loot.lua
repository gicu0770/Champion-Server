function onDeath(creature, corpse, killer, mostDamage, unjustified, mostDamage_unjustified)
	if not creature or creature:isPlayer() or creature:getMaster() then
    return
	end
	if not killer then
		return
	end

	if corpse or not corpse.itemid == 0 then
		if corpse and corpse.itemid ~= 0 and corpse ~= nil then 
			if creature and creature:isMonster() then
				local loot = extra_loot[creature:getName():lower()]
				if loot then
					local lootMnoznik = 0
					local lootSuma = 1
					if killer:hasBuff(STORE_LOOT_BOOST) then
						lootMnoznik = lootMnoznik + 0.2
					end
					if killer:hasBuff(MONSTER_SOUL_LOOT) then
						lootMnoznik = lootMnoznik + 0.1
					end
					if getGlobalBuff(BUFF_GLOBAL_LOOT) then
						lootSuma = lootSuma + 0.2
					end
					if creature:getSkull() > 6 then
						lootSuma = lootSuma + 0.2
					end
					if creature:getSkull() == 26 then
						lootSuma = 100000
					end
					if creature:getSkull() == 27 then
						lootSuma = lootSuma + 0.5
					end
					corpse:addExtraLoot(creature, loot, lootMnoznik+lootSuma)
				end
			end
		end
	end
end

function Container:addExtraLoot(creature, loot, lootMnoznik)
	local lootServerRate = configManager.getNumber(configKeys.RATE_LOOT)
	math.randomseed(os.time())
	for i = 1, #loot.items do
		local lootRate = loot.items[i].chance * lootServerRate * lootMnoznik
		if math.random(1, 100000) <= lootRate * 5 then
			local count = 0
			if loot.items[i].count then
				if loot.items[i].countMax then
					count = math.random(loot.items[i].count, loot.items[i].countMax)
				else
					count = loot.items[i].count
				end
			else
				if loot.items[i].countMax then
					count = math.random(1, loot.items[i].countMax)
				end
			end
	
			self:addItem(loot.items[i].id, count )
			local pos = self:getPosition()
			Game.sendAnimatedText(loot.items[i].napis, pos, loot.items[i].color, "Reggae One-20px-bordered")
		end
	end
end