function onExtendedOpcode(player, opcode, buffer)
   if opcode == ExtendedOPCodes.CODE_DAILY_REWARDS then
     local status, json_data =
       pcall(
       function()
         return json.decode(buffer)
       end
     )
     if not status then
       return false
     end
     
     PassLevel = nil
     
       local reward = getDailyRewards(player)
       local day = getDay(player)
     if json_data.action == "OPEN" then
       player:sendExtendedOpcode(ExtendedOPCodes.CODE_DAILY_REWARDS, json.encode({myData = DAILY_REWARDS}))
       player:sendExtendedOpcode(ExtendedOPCodes.CODE_DAILY_REWARDS, json.encode({reward = reward}))
       player:sendExtendedOpcode(ExtendedOPCodes.CODE_DAILY_REWARDS, json.encode({day = day}))
     end
     
if json_data.ID then
   PassLevel = json_data.ID
end

local function SecondsToShortTime(seconds)
    if seconds <= 0 then
      return "00:00:00"
    else
      local hours = string.format("%02.f", math.floor(seconds / 3600))
      local mins = string.format("%02.f", math.floor(seconds / 60 - (hours * 60)))
      local secs = string.format("%02.f", math.floor(seconds - hours * 3600 - mins * 60))
      return hours .. ":" .. mins .. ":" .. secs
    end
  end

   local DailyRewards = getDailyRewards(player)
   local day = getDay(player)
   if DailyRewards == 0 then
    for i = 1, #DAILY_REWARDS do
     if i == PassLevel then
        local buffTime = DAILY_REWARDS[i].item.bufftime
        local buffTimeShort = "1h" -- SecondsToShortTime(buffTime)
        if player:isPremium() then buffTime = buffTime * 2 buffTimeShort = "2h" end
        player:removeBuff(DAILY_REWARDS[i].item.buff)
        player:addBuff(DAILY_REWARDS[i].item.buff,buffTime)
        player:sendExtendedOpcode(71, json.encode({text = "Your "..buffTimeShort.." of "..DAILY_REWARDS[i].item.buffName.." has started", color = "#f7ef8a"}))
        setDailyRewards(player, 1)
        setDay(player, day + 1)
      end
     end
    end
 end
